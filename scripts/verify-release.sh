#!/usr/bin/env bash
#
# verify-release.sh — post-publication integrity check for a SpaceKai release.
#
# Usage:
#   ./scripts/verify-release.sh <assets-dir> [release-tag]
#
# Checks (exit != 0 when any critical check FAILs):
#   1. Exactly one standalone release APK (SpaceKai-vX.Y.Z.apk).
#   2. The APK name is a release variant (no debug/unsigned/aligned/ABI split/foss).
#   3. SHA256SUMS.txt exists and every listed checksum matches the downloaded file.
#   4. The APK's versionCode beats the highest code ever published (downgrade
#      guard — Android refuses updates with "Application non installée" when
#      the new APK's versionCode is lower than the installed one's).
#   5. The APK is signed with the pinned SpaceKai key (fingerprint match — a
#      rotated key would be refused by Android on install-over).
#   6. Desktop packages present (warn only — an APK-only release is allowed).
#
# Runs in CI after `gh release download`, or locally after downloading a
# release manually. The checksum file is trusted as the source of truth: it is
# generated by the release pipeline with plain basenames, so each `hash  name`
# line must resolve to a file present in the assets directory.

set -euo pipefail

DIR="${1:-assets}"
TAG="${2:-}"

if [ ! -d "$DIR" ]; then
  echo "::error::Assets directory '$DIR' not found." >&2
  exit 1
fi

FAILED=0
warn() { echo "  WARN: $1"; }
pass() { echo "  PASS: $1"; }
fail() { echo "  FAIL: $1"; FAILED=1; }

echo "== SPACEKAI RELEASE VERIFICATION  ${TAG:+tag $TAG}"
echo ""

echo "## Android"
# 1. Exactly one APK — never a split/debug/unsigned set.
APKS=$(find "$DIR" -maxdepth 1 -name '*.apk' 2>/dev/null | sort)
COUNT=$(printf '%s\n' "$APKS" | grep -c '\.apk$' || true)
if [ "$COUNT" -ne 1 ]; then
  fail "expected exactly 1 release APK, found $COUNT"
  APK=""
else
  APK="$APKS"
  pass "single APK: $(basename "$APK")"
fi

# 2. The single APK must be a release variant.
if [ -n "$APK" ]; then
  if echo "$(basename "$APK")" | grep -qE 'debug|unsigned|aligned|arm64|armv7|x86|foss|universal'; then
    fail "APK name looks like a non-release variant: $(basename "$APK")"
  else
    pass "APK name is a release variant"
  fi
  if [ -n "$TAG" ]; then
    if [ "$(basename "$APK")" = "SpaceKai-$TAG.apk" ]; then
      pass "APK name matches release tag: SpaceKai-$TAG.apk"
    else
      fail "APK name does not match tag: expected SpaceKai-$TAG.apk, got $(basename "$APK")"
    fi
  fi
fi

echo ""
echo "## Checksums"
# 3. SHA256SUMS.txt present and every line verified against the downloaded file.
SUMS="$DIR/SHA256SUMS.txt"
if [ ! -f "$SUMS" ]; then
  fail "SHA256SUMS.txt missing"
else
  pass "SHA256SUMS.txt present"
  LINES=0
  while read -r expected file; do
    [ -n "$expected" ] || continue
    # Git Bash's sha256sum marks binary files with a leading '*' — strip it
    # so the filename matches the downloaded asset either way.
    file="${file#\*}"
    LINES=$((LINES + 1))
    if [ ! -f "$DIR/$file" ]; then
      fail "checksum entry '$file' not found among downloaded assets"
      continue
    fi
    actual=$(sha256sum "$DIR/$file" | awk '{print $1}')
    if [ "$actual" = "$expected" ]; then
      pass "sha256 OK for $file"
    else
      fail "sha256 MISMATCH for $file"
    fi
  done < "$SUMS"
  if [ "$LINES" -eq 0 ]; then
    fail "SHA256SUMS.txt is empty"
  fi
fi

echo ""
echo "## Signing identity (fingerprint pin)"
# 4b. The APK must be signed with the SpaceKai key — the exact certificate
# pinned below (CN=Sankamusic Dev, verified against the genuine v0.3.0 and
# v0.3.2 release assets). A release signed with any other key is refused
# before anyone downloads it: Android treats a different signing key as a
# conflicting app and shows "Application non installée" on install-over,
# which would silently break the in-app update the release is meant to prove.
#
# Extracts the signing cert from META-INF/*.RSA via unzip + openssl (both
# preinstalled on ubuntu-latest; no JDK needed) — same value keytool reports.
SPACEKAI_CERT_SHA256="D9:BA:FD:4F:AB:87:15:DB:03:B2:67:11:E3:A8:42:A9:6E:90:BA:BA:BF:1A:83:3F:63:57:A9:49:B4:09:63:7E"
if [ -n "$APK" ]; then
  if command -v unzip >/dev/null 2>&1 && command -v openssl >/dev/null 2>&1; then
    RSA_FILE=$(unzip -Z1 "$APK" 'META-INF/*.RSA' 2>/dev/null | head -1)
    if [ -z "$RSA_FILE" ]; then
      fail "no META-INF/*.RSA signing block found in APK — unsigned or v1-scheme-less APK"
    else
      CERT_FP=$(
        unzip -p "$APK" "$RSA_FILE" 2>/dev/null |
          openssl pkcs7 -inform DER -print_certs 2>/dev/null |
          openssl x509 -fingerprint -sha256 -noout 2>/dev/null |
          sed 's/.*=//; s/://g' | tr '[:upper:]' '[:lower:]'
      )
      EXPECTED=$(echo "$SPACEKAI_CERT_SHA256" | sed 's/://g' | tr '[:upper:]' '[:lower:]')
      if [ -n "$CERT_FP" ] && [ "$CERT_FP" = "$EXPECTED" ]; then
        pass "APK signed with the pinned SpaceKai key (SHA-256 $SPACEKAI_CERT_SHA256)"
      else
        fail "APK signing fingerprint MISMATCH — got '$CERT_FP', expected '$SPACEKAI_CERT_SHA256'. A different key would be refused by Android on install-over."
      fi
    fi
  else
    warn "unzip/openssl not available — signing fingerprint not verified in this environment"
  fi
fi

echo ""
echo "## Version code (downgrade guard)"
# 4. The published APK must not be a downgrade: its versionCode has to be
# strictly greater than the highest versionCode ever shipped. Real incident
# (2026-08-25): v1.1.6 series shipped code 66, then v1.7.5 shipped 61 — the
# check passed against the previous tag, but Android rejected the install for
# anyone on v1.1.6-3 with "Application non installée". Keep MIN in sync with
# apply-release-pipeline.sh / release-publish.sh and bump it when a release
# ships a higher code. Highest shipped = 72 (v1.8.1; v1.8.0 = 71).
MIN_VERSION_CODE=72
if [ -n "$APK" ] && command -v unzip >/dev/null 2>&1; then
  unzip -p "$APK" AndroidManifest.xml > "$DIR/.manifest.bin" 2>/dev/null || true
  CODE=$(perl -e '
    my $f = shift; open my $fh, "<:raw", $f or die; local $/; my $d = <$fh>; close $fh;
    my $idx = 0;
    while (($idx = index($d, "\x08\x00\x00\x10", $idx)) != -1) {
      my $val = unpack("V", substr($d, $idx+4, 4));
      if ($idx < 20000 && $val > 1 && $val < 500) { print $val; last; }
      $idx += 4;
    }
  ' "$DIR/.manifest.bin" 2>/dev/null || true)
  rm -f "$DIR/.manifest.bin"
  if [[ "$CODE" =~ ^[0-9]+$ ]]; then
    if [ "$CODE" -gt "$MIN_VERSION_CODE" ]; then
      pass "versionCode $CODE > $MIN_VERSION_CODE (beats full history)"
    else
      fail "versionCode $CODE is NOT greater than the highest ever published ($MIN_VERSION_CODE) —"
      fail "Android would refuse this as a downgrade ('Application non installée')"
    fi
  else
    warn "could not read versionCode from AndroidManifest.xml (perl/unzip unavailable?)"
  fi
fi

echo ""
echo "## Desktop"
DESKTOP=$(find "$DIR" -maxdepth 1 \( -name '*.AppImage' -o -name '*.msix' -o -name '*.dmg' -o -name '*windows-installer.zip' \) 2>/dev/null | sort)
if [ -z "$DESKTOP" ]; then
  warn "no desktop packages found (APK-only release)"
else
  for f in $DESKTOP; do
    pass "desktop package: $(basename "$f")"
  done
fi

echo ""
if [ "$FAILED" -eq 1 ]; then
  echo "RESULT: VERIFICATION FAILED"
  exit 1
fi
echo "RESULT: ALL CHECKS PASSED"